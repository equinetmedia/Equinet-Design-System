#!/usr/bin/env python3
"""
Equinet — vendor the Lucide icon library.

    npm install lucide-static
    python tools/vendor-lucide.py [path/to/node_modules/lucide-static]

Copies every Lucide glyph into assets/icons/lucide/ unmodified, alongside its
licence, and regenerates INDEX.md.

WHY THE LIBRARY IS VENDORED AT ALL
    `ICON-REFERENCE.md` told a build to search Lucide. A Claude Design session
    has no network and no package, so that resolved to "recall 24 x 24 path
    data from memory", and most builds sensibly declined — which is why pages
    arrived with no substituted icons. A build cannot fetch; the repo has to
    already contain the thing it is told to reach for.

WHY UNMODIFIED
    So any glyph can be diffed against upstream and shown to be the icon it
    claims to be. They therefore ship at Lucide's native stroke-width 2, and
    the house weight of 1 is applied by `.eq-icon` in bundle.css rather than
    by editing 2159 files.

WHY THEY ARE NOT IN manifest.json
    That file catalogues Equinet's own artwork — background, roles, palette
    mapped to tokens. Adding a third-party library would take it past 1 MB and
    bury the 118 assets whose discovery is its entire job.

RUN THIS WHEN
    Lucide publishes a version worth taking, or a build reports a glyph it
    could not find (the Phase 2 close-out asks for exactly that number).
"""
import json
import os
import shutil
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEST = os.path.join(ROOT, "assets", "icons", "lucide")

# The shortlist that covers most Equinet pages, surfaced at the top of the
# index so a build does not scan 2159 names for a calendar.
COMMON = """x circle-check external-link arrow-right arrow-left arrow-up-right chevron-right chevron-down
search message-square-quote heading text-quote book-open book-open-text code-xml badge-check repeat
calendar calendar-clock clock timer target trending-up trending-down chart-column chart-line chart-pie
users user-check building-2 factory settings cog zap shield-check file-text files database workflow
git-branch layers link map-pin mail phone play download quote lightbulb compass scale gauge filter
sparkles bot brain network server lock eye check plus minus info circle-alert circle-help
list-checks square-check hand-coins handshake rocket wrench puzzle route signpost microscope""".split()


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else "node_modules/lucide-static"
    icons = os.path.join(src, "icons")
    if not os.path.isdir(icons):
        print(f"no icons at {icons}\n\n  npm install lucide-static\n")
        return 2

    version = "unknown"
    pkg = os.path.join(src, "package.json")
    if os.path.exists(pkg):
        version = json.load(open(pkg)).get("version", "unknown")

    os.makedirs(DEST, exist_ok=True)
    for old in os.listdir(DEST):
        if old.endswith(".svg"):
            os.remove(os.path.join(DEST, old))

    names = []
    for fn in sorted(os.listdir(icons)):
        if fn.endswith(".svg"):
            shutil.copy2(os.path.join(icons, fn), os.path.join(DEST, fn))
            names.append(fn[:-4])

    for extra in ("LICENSE", "LICENCE", "license"):
        p = os.path.join(src, extra)
        if os.path.exists(p):
            shutil.copy2(p, os.path.join(DEST, "LICENSE"))
            break

    tags = {}
    tp = os.path.join(src, "tags.json")
    if os.path.exists(tp):
        tags = json.load(open(tp))

    missing = [n for n in COMMON if n not in set(names)]
    if missing:
        print(f"note: {len(missing)} shortlist name(s) absent from this Lucide "
              f"version — {', '.join(missing)}")

    write_index(names, tags, version)
    print(f"vendored {len(names)} glyphs from lucide-static {version}")
    print(f"index: {os.path.getsize(os.path.join(DEST, 'INDEX.md')):,} bytes")
    return 0


def write_index(names, tags, version):
    common = [n for n in COMMON if n in set(names)]
    head = f"""---
id: lucide-index
status: generated
read_when: >-
  Choosing a substituted icon. Lists all {len(names)} vendored Lucide glyphs, with the
  {len(common)} that cover most Equinet pages first. Generated by tools/vendor-lucide.py.
depends_on: assets/icons/ICON-REFERENCE.md
---

# Lucide index

Lucide v{version}, ISC — all **{len(names)}** glyphs, unmodified, licence in `LICENSE`.

**Inline the file you want. Never reproduce path data from memory**, even for
an icon you think you know: that was why pages came back with none. The house
stroke weight is applied by `.eq-icon` in `bundle.css`, so do not edit the
files — they stay diffable against upstream.

## Start here — the {len(common)} that cover most Equinet pages

If one of these fits, take it and stop reading.

{' '.join('`%s`' % n for n in common)}

## Everything else

Search by what the icon *does*. Lucide's own keywords follow the name where
it ships them.
"""
    rest = [n for n in names if n not in set(common)]
    body = "\n".join(
        f"`{n}`" + (f" · {', '.join(tags[n][:5])}" if tags.get(n) else "") for n in rest
    )
    with open(os.path.join(DEST, "INDEX.md"), "w", encoding="utf-8") as fh:
        fh.write(head + "\n" + body + "\n")


if __name__ == "__main__":
    sys.exit(main())
